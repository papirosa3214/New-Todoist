import { createPortal } from "react-dom";
import { Icon } from "./UI";

// ═══════════ Микрофон над клавиатурой ═══════════
//
// Owner 2026-08-13 (пятый заход, итог): «влезть» физически поверх
// системной accessory-панели iOS (стрелочки/Done) невозможно — не баг
// вёрстки, архитектурное ограничение платформы. Та панель не DOM-узел
// страницы, а часть системного UI-слоя браузера (browser chrome),
// который композитится ОС/движком поверх содержимого страницы; веб-
// контенту (z-index, position:fixed — не важно что) туда доступа нет в
// принципе. Проверено не на глаз: тот же принцип независимо подтверждают
// Apple Developer Forums на соседнем случае — position:fixed контент
// физически обрезается, если пытается зайти под системные browser
// controls, а не отрисовывается поверх них.
// Четвёртый заход (компенсация -121px, прозрачный фон, «слиться» с
// системной панелью) исходил из неверной посылки — что раз нельзя
// добавить кнопку В панель, можно хотя бы нарисовать поверх нее; владелец
// проверил вживую — кнопка физически недоступна для тапа (закрыта
// системным слоем). Возврат к рабочему месту: `bottom: var(--kb-inset)`,
// ровно ВЫШЕ системной панели, там кнопка реально кликабельна — это
// подтверждённая рабочая зона, не гипотеза. Визуально — не полноширинная
// плашка (её раньше сочли слишком «в лоб»), а компактная плавающая
// кнопка-таблетка, полупрозрачный фон+блюр, чтобы не выглядеть чужеродной
// панелью, а лёгким плавающим элементом.
//
// Восьмой заход (owner 2026-08-13, живой баг на телефоне) — ГИПОТЕЗА НЕ
// ПОДТВЕРДИЛАСЬ: считал, что причина — кратковременный провал --kb-inset
// к 0 при blur/focus между полями, защищался
// max(var(--kb-inset), env(safe-area-inset-bottom)). Не сработало —
// safe-area-inset-bottom (~34px) не может исправить провал внутрь зоны
// клавиатуры (~300px+), защита била не по той цели.
//
// Девятый заход (owner 2026-08-13) — НАЙДЕНО И ИСПРАВЛЕНО. Диагностика на
// живом телефоне (временный debug-баннер, снят после разбора): при фокусе
// на «Заметка» (поле ниже по форме, требует авто-скролла) сам баннер
// (position:fixed; top:0) физически «уехал выше» видимой области экрана —
// возможно только если vv.offsetTop > 0. Разбор:
//   --kb-inset считается как innerHeight − vv.height − vv.offsetTop
//   (useVisualViewportInset.ts) — верно для элементов «в потоке» документа
//   (они физически панорамируются вместе со страницей, offsetTop
//   компенсирует то, что часть уже скрыта паном). Но для position:fixed
//   элемента это ДВОЙНОЙ учёт: сам пан уже сдвигает его физическое
//   положение независимо от CSS, а --kb-inset вычитает offsetTop ЕЩЁ РАЗ —
//   при offsetTop≈37px кнопка садилась на те же ~37px глубже в зону
//   клавиатуры/accessory-панели, чем нужно.
// Фикс: отдельная переменная --kb-height = innerHeight − vv.height, БЕЗ
// offsetTop — чистая высота клавиатуры, верная для fixed-элементов,
// которые сами не участвуют в панорамировании документа. --kb-inset не
// тронут (TaskDetailScreen и padding формы — «в потоке», там формула с
// offsetTop верна). max(..., safe-area-inset-bottom) убран — он никогда
// не срабатывал (413px инсета ≫ 34px safe-area), а теперь и не нужен:
// --kb-height корректен без запасного пути.
export function MicKeyboardBar({
  onStart,
  ariaLabel,
}: {
  onStart: () => void;
  ariaLabel: string;
}) {
  return createPortal(
    <div
      // Прижата к правому краю (right-[18px] — тот же отступ, что у FAB
      // в UI.tsx, канон плавающих круглых кнопок этого проекта), а не по
      // центру экрана: владелец 2026-08-13 попросил сдвинуть её
      // максимально вправо.
      className="fixed right-[18px] z-[45] pb-2"
      style={{ bottom: "var(--kb-height, 0px)" }}
    >
      <button
        type="button"
        // Клик по кнопке не должен красть фокус у textarea (иначе blur
        // сорвал бы voiceTarget/keyboardFieldFocused раньше, чем onClick
        // успеет отработать) — preventDefault на mousedown держит фокус на
        // текстовом поле, стандартный приём для тулбар-кнопок.
        onMouseDown={(e) => e.preventDefault()}
        onClick={onStart}
        aria-label={ariaLabel}
        // Тот же «стеклянный» приём, что уже держат ScreenHeader/
        // SearchScreen (bg-bg/90 backdrop-blur-xl, components/UI.tsx) — не
        // свой рецепт, канон проекта, просто ниже opacity (70, не 90) и
        // сильнее blur (xl вместо sm): та панель на всю ширину экрана под
        // контентом, эта — маленький плавающий круг на фоне клавиатуры,
        // ему нужна не почти-непрозрачная подложка, а настоящее стекло.
        // Owner 2026-08-13 (девятый заход): владелец попросил именно
        // Apple-style «жидкое стекло», не плоский blur — канон проекта
        // (backdrop-blur-xl без saturate) даёт этот плоский эффект, отсюда
        // «видно, что инородный». Настоящий iOS material (UIBlurEffect) —
        // это ВСЕГДА blur + saturate вместе: насыщенность того, что под
        // стеклом, сама по себе продаёт «стеклянность», один blur без неё
        // выглядит как обычная полупрозрачная плашка. backdrop-saturate-150
        // добавлен ТОЛЬКО здесь (точечно, под конкретную просьбу), канон в
        // UI.tsx не тронут — если понравится, распространить туда отдельным
        // заходом, не молча заодно. Второй приём — тонкий inset-блик по
        // верхнему краю (имитирует свет, ловящийся кромкой стекла) поверх
        // уже существующей внешней тени: border-stroke сам по себе
        // одинаковый со всех сторон, блик делает верх чуть светлее низа,
        // как и настоящее выпуклое стекло.
        className="tap-scale w-11 h-11 rounded-full bg-bg/70 backdrop-blur-xl backdrop-saturate-150 border border-stroke shadow-[0_2px_10px_rgba(0,0,0,.35),inset_0_1px_0_rgba(255,255,255,.14)] flex items-center justify-center"
      >
        <Icon name="mic" size={20} className="text-text" />
      </button>
    </div>,
    document.body,
  );
}
