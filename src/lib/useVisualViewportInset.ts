// ═══════════ ИНСЕТ ЭКРАННОЙ КЛАВИАТУРЫ (window.visualViewport) ═══════════
//
// Зачем это вообще нужно: index.html ставит в мета-теге viewport токен
// interactive-widget=resizes-content — по спеке он должен пересчитывать
// 100dvh под открытую экранную клавиатуру, и в Chrome/Android это
// действительно работает: dvh-высота сама ужимается, форма поднимается.
// WebKit (Safari, а значит и режим «с домашнего экрана» на iPhone) этот
// токен не реализует вообще (аудит поведения форм, 2026-08-11) — при
// открытии клавиатуры layout-вьюпорт, от которого считается 100dvh,
// остаётся прежним, и всё, что стоит внизу экрана на нижнем отступе,
// уезжает под клавиатуру.
//
// Единственный API, который WebKit действительно обновляет при появлении
// клавиатуры — window.visualViewport: его height и offsetTop меняются,
// даже когда layout-вьюпорт не сдвинулся ни на пиксель. Этот хук слушает
// его и пишет высоту «съеденной» клавиатурой области в CSS-переменную
// --kb-inset на <html> (documentElement). Переменная, а не React-стейт:
// инсет должен быть доступен сразу всему дереву компонентов, которым
// нужно поднять нижний отступ над клавиатурой (через
// calc(текущий_отступ + var(--kb-inset, 0px))), а запись в CSSOM напрямую
// не тянет за собой лишний ре-рендер всего поддерева при каждом кадре
// анимации клавиатуры — resize/scroll на visualViewport может стрелять
// довольно часто.
//
// Дефолт 0px на случай отсутствия API или пока хук ещё не успел
// отработать — задан отдельно, в src/index.css (:root), не здесь: если
// JS не выполнился вовсе (или window.visualViewport нет в этом браузере),
// вёрстка не должна на это ломаться, а calc() с несуществующей
// переменной посчитал бы как invalid.
import { useEffect } from "react";

export function useVisualViewportInset() {
  useEffect(() => {
    const vv = window.visualViewport;
    // Браузер без visualViewport (старый WebKit, некоторые тестовые
    // рендереры вроде headless-окружений без полной реализации API) —
    // просто ничего не делаем, переменная остаётся дефолтным 0px из
    // index.css, и вся вёрстка ведёт себя ровно так, как будто этого
    // хука нет.
    if (!vv) return;

    const update = () => {
      // window.innerHeight — высота layout-вьюпорта, той самой, от
      // которой считается 100dvh; на WebKit она НЕ меняется при
      // появлении клавиатуры. vv.height — высота реально видимой части
      // страницы, она уменьшается ровно на высоту клавиатуры.
      // vv.offsetTop — насколько visualViewport сдвинут вниз относительно
      // layout-вьюпорта (ненулевой, когда страница проскроллена так, что
      // верх видимой области уже не совпадает с верхом документа).
      // Разность innerHeight − vv.height − vv.offsetTop — это то, что
      // сейчас закрыто снизу и не входит в видимую область: клавиатура
      // (в этом приложении больше нечему — html.app-shell-locked уже
      // прячет браузерную адресную строку/панель, см. index.css). Math.max
      // с нулём — защита от отрицательных значений на переходных кадрах
      // анимации открытия/закрытия клавиатуры и от округления; минусовый
      // отступ был бы хуже нулевого.
      const inset = Math.max(0, window.innerHeight - vv.height - vv.offsetTop);
      document.documentElement.style.setProperty("--kb-inset", `${inset}px`);
    };

    // Считаем сразу при монтировании — а не только по первому событию —
    // на случай, если хук подключается уже при открытой клавиатуре
    // (например, после ремонта Layout при быстрой навигации).
    update();

    // 'resize' — собственно открытие/закрытие клавиатуры (высота
    // visualViewport меняется). 'scroll' — Safari разрешает двигать сам
    // visualViewport пальцем, пока клавиатура уже открыта (offsetTop
    // меняется без отдельного resize) — без этого слушателя инсет отстал
    // бы от реальной картинки при панорамировании над клавиатурой.
    vv.addEventListener("resize", update);
    vv.addEventListener("scroll", update);

    return () => {
      vv.removeEventListener("resize", update);
      vv.removeEventListener("scroll", update);
      // Сброс на дефолт при размонтировании — тот же дефолт, что и в
      // index.css, чтобы не оставить «залипший» ненулевой инсет для
      // экранов, которые этот конкретный монтированный хук больше не
      // обслуживает (Layout размонтируется/монтируется заново при
      // переходах на /login и /register, которые рендерятся вне него).
      document.documentElement.style.setProperty("--kb-inset", "0px");
    };
  }, []);
}
