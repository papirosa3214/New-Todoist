// ═══════════ Виброотклик (Taptic Engine) ═══════════
//
// Плагин @capacitor/haptics, 20.08.2026, просьба владельца: отклик там, где
// палец «возюкает» по полю задач — перетаскивание в «Сегодня», на доске, в
// списке подзадач, свайп строки — и на каждой клавише своей клавиатуры.
//
// Три вещи, из-за которых это модуль, а не прямые вызовы Haptics по местам:
//
//  1) На ВЕБЕ вызывать нечего. Capacitor на вебе подменяет плагин
//     web-реализацией поверх navigator.vibrate, а в Safari (и в любом
//     WebKit) его нет вовсе — вызов кончается отказом промиса. Гасим по
//     isNativePlatform(), а не try/catch на каждой клавише.
//  2) Промисы НИКОГДА не ждём и не даём им всплыть. Виброотклик — украшение;
//     отказ плагина не имеет права уронить обработчик жеста или оставить
//     unhandled rejection в логе устройства (а лог сейчас единственный канал
//     диагностики на телефоне, см. docs/lessons/2026-08-18-ios-build...).
//  3) Частота. dnd-kit шлёт onDragOver каждый кадр движения пальца, и без
//     ограничителя Taptic Engine получает десятки вызовов в секунду: iOS
//     их просто глотает (генератор занят), отклик становится рваным, а не
//     чаще. Вызывающий код и так бьёт только по СМЕНЕ цели, MIN_GAP_MS —
//     страховка на случай дребезга у границы двух ячеек.
import { Capacitor } from "@capacitor/core";
import { Haptics, ImpactStyle } from "@capacitor/haptics";

const NATIVE = Capacitor.isNativePlatform();

// 40 мс ≈ 25 откликов в секунду — предел, за которым Taptic Engine всё
// равно перестаёт различать отдельные срабатывания. Пороги ниже этого
// числа не подбирались «на слух»: замерить вибрацию нечем, поэтому взят
// технический потолок, а не вкусовое значение.
const MIN_GAP_MS = 40;
let lastAt = 0;

function fire(run: () => Promise<unknown>): void {
  if (!NATIVE) return;
  const now = performance.now();
  if (now - lastAt < MIN_GAP_MS) return;
  lastAt = now;
  void run().catch(() => {});
}

/**
 * Взяли объект пальцем: карточка «оторвалась» от полотна.
 * Medium — самый заметный из трёх, но не Heavy: подъём карточки не удар.
 */
export function hapticGrab(): void {
  fire(() => Haptics.impact({ style: ImpactStyle.Medium }));
}

/**
 * Перетаскиваемое пересекло границу — другой час, другая колонка, другое
 * место в списке. Ровно тот жанр, под который сделан
 * UISelectionFeedbackGenerator (им же щёлкает системный пикер).
 */
export function hapticCross(): void {
  fire(() => Haptics.selectionChanged());
}

/** Отпустили: объект лёг на место. Лёгкий — это касание, не удар. */
export function hapticDrop(): void {
  fire(() => Haptics.impact({ style: ImpactStyle.Light }));
}

/**
 * Клавиша своей экранной клавиатуры. У системной клавиатуры iOS отклик на
 * клавишах включается в настройках («Звук и тактильные сигналы» →
 * «Тактильный отклик клавиатуры»), но WKWebView своей клавиатуре его не
 * даёт — за неё это делаем мы.
 */
export function hapticKey(): void {
  fire(() => Haptics.impact({ style: ImpactStyle.Light }));
}
