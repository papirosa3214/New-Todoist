import { chromium } from "playwright";
import { execSync } from "node:child_process";
const BASE = "http://127.0.0.1:3112";
const OUT = "qa-shots/dorabotka2";
const PICK = "button:has-text('minimax'), button:has-text('local-qwen'), button:has-text('MiniMax'), button:has-text('qwen')";
execSync("python3 -c \"import sqlite3;c=sqlite3.connect('/tmp/qa-cl/.state/agent.sqlite3');c.execute(\\\"delete from state where key='chat_selection'\\\");c.commit()\"");
const b = await chromium.launch({ channel: "chrome", args: ["--no-sandbox"] });
const p = await (await b.newContext({ viewport: { width: 420, height: 912 } })).newPage();
await p.goto(`${BASE}/static/app/index.html#/chat`, { waitUntil: "load" });
await p.waitForTimeout(3000);
await p.locator(PICK).first().click();
await p.waitForTimeout(500);
await p.locator("button", { hasText: "local-qwen" }).last().click();
await p.waitForTimeout(1500);
console.log("после выбора:", (await p.locator(PICK).first().innerText()).replace(/\n/g, " | "));
await p.screenshot({ path: `${OUT}/40-picked-local-qwen.png`, fullPage: true });
await p.reload({ waitUntil: "load" });
await p.waitForTimeout(3000);
console.log("после перезагрузки:", (await p.locator(PICK).first().innerText()).replace(/\n/g, " | "));
await p.screenshot({ path: `${OUT}/41-after-reload-back-to-minimax.png`, fullPage: true });
await b.close();
