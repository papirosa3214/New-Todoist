export function instrumentById(id: string): Instrument | undefined {
  return INSTRUMENTS.find((i) => i.id === id);
}

/** Набор символов, которые нужны справочнику: извлекаем из описаний инструментов. */
export function instrumentQuoteSymbols(): string[] {
  const set = new Set<string>();
  for (const i of INSTRUMENTS) for (const s of i.quoteSymbols) set.add(s);
  return [...set];
}