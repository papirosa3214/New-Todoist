import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 420, height: 912 }, locale: "ru-RU", timezoneId: "Europe/Moscow" });
const errs = [];
p.on("console", m => { if (m.type() === "error") errs.push(m.text()); });
p.on("pageerror", e => errs.push("pageerror: " + e.message));
await p.goto("http://127.0.0.1:4104/upcoming", { waitUntil: "networkidle" });
await p.waitForTimeout(1500);
await p.click('button[aria-label="Ещё"]');
await p.waitForTimeout(600);
await p.click('text="Неделя"');
await p.waitForTimeout(2500);
const txt = await p.evaluate(() => document.body.innerText);
console.log("=== Неделя ===");
console.log(txt.slice(0, 1200));
console.log("QA present:", txt.includes("QA-проверка"));
await p.screenshot({ path: "workspace/qa-recheck/out-probe/tridnya.png" });
console.log("errors:", JSON.stringify(errs.slice(0, 6)));
await b.close();
