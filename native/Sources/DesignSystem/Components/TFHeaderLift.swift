import SwiftUI

// Подъём шапок ближе к «динамическому острову» — владелец 01.09.2026:
// «подтяни все экраны на строчку выше», между статус-баром и заголовком
// стояла лишняя пустая строка.
//
// Константа ОДНА на приложение и применяется ко всем шапкам сразу: экраны
// уже один раз разъехались из-за того, что каждый задавал геометрию сам
// (см. историю правок 01.09.2026 — «разнобой в цветах и шрифтах»).
public enum TFHeaderMetrics {
    /// Ровно одна строка заголовка `.title` (17pt, line height ≈ 22).
    public static let topLift: CGFloat = 22
}

public extension View {
    /// Поднимает шапку на строку вверх. У шапки, вставленной через
    /// `safeAreaInset(edge: .top)`, вместе с ней поднимается и контент под
    /// ней — inset становится на столько же меньше.
    func tfHeaderLift() -> some View {
        padding(.top, -TFHeaderMetrics.topLift)
    }
}
