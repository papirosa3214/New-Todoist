import {beforeAll,it,expect,vi} from "vitest";
import {Type} from "typebox";
import db,{migrate} from "../src/db.js";
import {runMigrations} from "../src/migrations.js";
import {createUniversalTaskflow} from "../src/runtime/universalTaskflow.js";
import {toolRequestStore,checkToolRequestStore} from "../src/runtime/toolRequestStore.js";
beforeAll(()=>{migrate();runMigrations();});
const decode=(r:any)=>JSON.parse(r.content[0].text);
it("persists results, deduplicates reordered arguments and rejects changed arguments/context",async()=>{
 const execute=vi.fn(async()=>({content:[{type:"text",text:"created"}]}));
 const op={name:"taskflow_comment",description:"write",parameters:Type.Object({id:Type.String(),text:Type.String()}),execute};
 const c={actor:"role_builder",role:"builder",mode:"work",runId:"one",taskId:"task-one"};
 const p={action:"invoke",operation:op.name,version:1,arguments:{id:"task-one",text:"hi"},request_id:"persisted"};
 const api=createUniversalTaskflow([op],c,toolRequestStore);
 expect(decode(await api.execute("a",p)).ok).toBe(true);
 const reopened=createUniversalTaskflow([op],{...c,runId:"two"},toolRequestStore);
 expect(decode(await reopened.execute("b",{...p,arguments:{text:"hi",id:"task-one"}})).ok).toBe(true);
 expect(execute).toHaveBeenCalledTimes(1);
 expect(decode(await reopened.execute("c",{...p,arguments:{id:"task-one",text:"different"}})).error.code).toBe("CONFLICT");
 const another=createUniversalTaskflow([op],{...c,taskId:"task-two"},toolRequestStore);
 expect(decode(await another.execute("d",p)).error.code).toBe("CONFLICT");
 expect(decode(await another.execute("e",{action:"invoke",operation:"requests.status",version:1,arguments:{request_id:"persisted"}})).error.code).toBe("UNKNOWN_REQUEST");
});
it("keeps interrupted external changes unknown after a process restart",()=>{
 toolRequestStore.begin({actor:"role_builder",id:"crashed",scope:"x",hash:"x",operation:"taskflow_comment",state:"running"});
 db.prepare("UPDATE role_tool_requests SET instance='old-process' WHERE id='crashed'").run();
 expect(toolRequestStore.get("role_builder","crashed")?.state).toBe("unknown_outcome");
});
it("does not execute concurrent duplicates or retry uncertain failures",async()=>{
 let resolve:any;const pending=new Promise<any>(r=>resolve=r);
 const execute=vi.fn(async()=>pending);
 const op={name:"taskflow_comment",description:"write",parameters:Type.Object({}),execute};
 const c={actor:"role_builder",role:"builder",mode:"work",runId:"run"};
 const api=createUniversalTaskflow([op],c,toolRequestStore);
 const p={action:"invoke",operation:op.name,version:1,arguments:{},request_id:"concurrent"};
 const first=api.execute("first",p);
 expect(decode(await api.execute("second",p)).data.state).toBe("running");
 resolve({content:[]});await first;expect(execute).toHaveBeenCalledTimes(1);
 const failure=vi.fn(async()=>{throw new Error("connection lost");});
 const broken=createUniversalTaskflow([{...op,execute:failure}],c,toolRequestStore);
 const q={...p,request_id:"uncertain"};
 expect(decode(await broken.execute("x",q)).error.code).toBe("OPERATION_FAILED");
 await broken.execute("y",q);
 expect(failure).toHaveBeenCalledTimes(1);
 expect(toolRequestStore.get(c.actor,q.request_id)?.state).toBe("unknown_outcome");
});
it("watcher exercises real store and rolls its probe back",()=>{
 const before=(db.prepare("SELECT count(*) AS n FROM role_tool_requests").get() as any).n;
 expect(checkToolRequestStore()).toEqual({ok:true});
 expect((db.prepare("SELECT count(*) AS n FROM role_tool_requests").get() as any).n).toBe(before);
});
