// Отметка «печатает…» в чате координации (28.08.2026, владелец: «у меня в
// чате нету вообще никакой отметки о том, кто что в моменте там печатает, а
// она мне очень сильно нужна»).
//
// ПОЧЕМУ В ПАМЯТИ, А НЕ В БАЗЕ. Тот же довод, что у живой строки действий
// агента (routes/activity.ts): это состояние «прямо сейчас», у него нет
// истории и его нельзя пережить перезапуску — после рестарта никто не
// печатает по определению. Миграций здесь нет и быть не должно, хранение
// сообщений задача не трогает.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ. Отметку надо гасить, когда у участника закрылся
// последний сокет, а это знает ws.ts. Если бы реестр жил в routes/chat.ts,
// ws.ts пришлось бы импортировать маршруты — цикл (chat.ts уже импортирует
// ws.ts). Здесь связь односторонняя: этот модуль знает про ws.ts, ws.ts про
// него — нет, он только зовёт зарегистрированный обработчик onUserGone.
import db from "./db.js";
import { broadcastToUsers, onUserGone } from "./ws.js";
import { snapshotFor } from "./activeAgent.js";

/**
 * Сколько живёт отметка без подтверждения.
 *
 * У человека сигнал шлёт строка ввода на каждое нажатие (с прореживанием),
 * поэтому срок короткий: перестал печатать — через несколько секунд гаснет
 * само, даже если браузер закрыли рубильником.
 *
 * У агента срок длиннее: пока модель сочиняет ответ, она не может
 * параллельно дёрнуть инструмент — вызов идёт до генерации, а следующий
 * будет уже после. Минута с запасом покрывает типичный одиночный ход.
 *
 * Дальше этого «без подтверждения» отметка у агента НЕ держится: сервер
 * продлевает её при КАЖДОМ реальном запросе от агента (touchTyping ниже) —
 * см. правило в задаче a56f35f6, 29.08.2026. Поэтому TTL_AGENT_MS здесь —
 * это не «потолок тишины», а запас на случай, когда агент взял задачу и
 * ещё не успел сделать ни одного запроса (например, долго думает над
 * первым шагом).
 */
const TTL_HUMAN_MS = 8_000;
const TTL_AGENT_MS = 60_000;

/**
 * Окно «агент работает»: был запрос от учётки-агента за последние
 * IDLE_TTL_MS_AGENT миллисекунд — отметка горит, тише этого — гаснет.
 *
 * 30 секунд — компромисс:
 *  - длиннее типичной паузы между обращениями агента к серверу (чтение
 *    чата, шаги задачи, отправка сообщения): пока он в работе, продление
 *    приходит чаще, и окно не протухает;
 *  - короче человеческой задержки ответа, чтобы после последнего
 *    сообщения владельцу не пришлось ждать минуту;
 *  - короче серверного TTL у сообщения, чтобы отметка гасла раньше, чем
 *    владелец успеет переключиться на другое окно.
 *
 * Правило целиком (владелец, 29.08.2026, задача a56f35f6):
 * «был запрос от агента за последние N секунд — горит, затих — гаснет».
 * Сообщение владельца в этом правиле НЕ участвует — ни зажигать, ни
 * гасить отметку оно не должно.
 */
const IDLE_TTL_MS_AGENT = 30_000;

/** Уборка протухших — реже, чем сроки: клиент гасит отметку своим таймером
 *  по ttl_ms, серверный обход нужен, чтобы карта не росла, и чтобы тот, кто
 *  открыл экран позже, не увидел покойника в снимке (GET). */
const SWEEP_MS = 3_000;

interface Typist {
  name: string;
  /** Когда отметка протухает, мс эпохи. */
  until: number;
  /** Свой срок участника — уезжает в событие, чтобы клиент гасил отметку
   *  тем же временем, каким её завёл сервер. */
  ttl: number;
}

const typists = new Map<string, Typist>();

/** Все участники канала: чат общий, отметку видят все — как и сообщения. */
function allUserIds(): string[] {
  return (
    db.prepare("SELECT id FROM users").all() as Array<{ id: string }>
  ).map((r) => r.id);
}

function userRow(userId: string): { name: string; type: string } | undefined {
  return db.prepare("SELECT name, type FROM users WHERE id = ?").get(userId) as
    { name: string; type: string } | undefined;
}

function emit(
  userId: string,
  name: string,
  state: "typing" | "stop",
  ttl: number,
) {
  // Для агента подмешиваем «чем занят» из activeAgent.snapshotFor: фронт
  // получает «работает + смысл действия + название задачи» одним пакетом
  // и не должен ходить за дополнительным снимком. Для человека — пусто,
  // им карточка «Команда» не показывается (29.08.2026, 31f2759e).
  const active = state === "typing" ? snapshotFor(userId) : null;
  broadcastToUsers(allUserIds(), {
    type: "chat:typing",
    user_id: userId,
    name,
    state,
    // Срок относительный, а не «до какого времени»: часы телефона и сервера
    // расходятся на секунды, и абсолютная метка гасила бы отметку раньше
    // времени или держала бы её лишнее.
    ttl_ms: ttl,
    // Подпись для UI: «читает задачу "Время в трекере…"». title берётся
    // из task, к которой обращение, и обновляется через titleCache в
    // activeAgent.ts (TTL 5 мин).
    last_action: active?.lastAction || "",
    last_action_title: active?.lastActionTitle || "",
  });
}

/**
 * Зажечь отметку. Используется в двух местах:
 *  - человек шлёт каждое нажатие клавиши (роут /api/chat/typing);
 *  - ручное переопределение (state без 'stop') — сохранено для отладки и
 *    на случай, если человек захочет форсированно показать, что он сейчас
 *    набирает длинный ответ, не трогая клавиатуру.
 *
 * Для агента это больше НЕ источник правды: агент ничего сам не зовёт,
 * зажигание приходит из touchTyping() при первом же запросе к серверу.
 */
export function startTyping(userId: string): { ttl_ms: number } | null {
  const row = userRow(userId);
  if (!row) return null;
  const wasActive = typists.has(userId);
  const ttl = row.type === "ai" ? IDLE_TTL_MS_AGENT : TTL_HUMAN_MS;
  typists.set(userId, { name: row.name, until: Date.now() + ttl, ttl });
  // Событие «typing» рассылаем только при переходе offline → online, чтобы
  // фронт не получал шквал одинаковых событий на каждый запрос агента
  // (продление касается только серверного таймера, клиенту про него знать
  // незачем — он гасит по своему ttl_ms в первом событии).
  if (!wasActive) emit(userId, row.name, "typing", ttl);
  return { ttl_ms: ttl };
}

/**
 * Продлить отметку без рассылки события. Зовётся сервером на КАЖДОМ
 * запросе от учётки-агента (index.ts, общий preHandler) — это и есть
 * источник правды «агент работает» в задаче a56f35f6:
 *
 *   был запрос от агента к серверу за последние IDLE_TTL_MS_AGENT мс —
 *   отметка горит, тише — гаснет.
 *
 * Не шлём лишних событий на фронт: он и так держит отметку живой до
 * своего ttl_ms из первого события; на каждое обращение агента (а их в
 * длинной работе десятки) слать «typing» — это дребезг и лишняя нагрузка
 * на вебсокеты.
 *
 * Тихий no-op, если пользователь — человек: для него окно тишины
 * управляется клиентской строкой ввода, а серверный счётчик ей не нужен.
 */
export function touchTyping(userId: string): void {
  const row = userRow(userId);
  if (!row) return;
  if (row.type !== "ai") return;
  const wasActive = typists.has(userId);
  typists.set(userId, {
    name: row.name,
    until: Date.now() + IDLE_TTL_MS_AGENT,
    ttl: IDLE_TTL_MS_AGENT,
  });
  if (!wasActive) emit(userId, row.name, "typing", IDLE_TTL_MS_AGENT);
}

/**
 * Погасить отметку. Зовётся из трёх мест: строка ввода опустела/потеряла
 * фокус, сообщение отправлено (см. POST /api/chat) и участник закрыл
 * последний сокет.
 */
export function stopTyping(userId: string): void {
  const entry = typists.get(userId);
  if (!entry) return;
  typists.delete(userId);
  emit(userId, entry.name, "stop", 0);
}

/** Снимок для того, кто ТОЛЬКО ЧТО открыл экран: событие про начало печати
 *  ушло до его подписки, и без снимка он увидел бы пустоту при живом
 *  собеседнике. Та же дыра и то же лечение, что у GET активности задачи. */
export function currentTypists(): Array<{
  user_id: string;
  name: string;
  ttl_ms: number;
}> {
  const now = Date.now();
  const out = [];
  for (const [userId, entry] of typists) {
    if (entry.until <= now) continue;
    out.push({ user_id: userId, name: entry.name, ttl_ms: entry.until - now });
  }
  return out;
}

// Ушёл со связи — отметка не должна пережить его. Сокет держат Максим в
// браузере и резидент канала; агенты с ключом сокета не держат вовсе и
// гаснут по сроку — это и есть их «отвалился».
onUserGone(stopTyping);

const sweeper = setInterval(() => {
  const now = Date.now();
  for (const [userId, entry] of typists) {
    if (entry.until <= now) {
      typists.delete(userId);
      emit(userId, entry.name, "stop", 0);
    }
  }
}, SWEEP_MS);
// Таймер уборки не повод держать процесс живым.
sweeper.unref?.();
