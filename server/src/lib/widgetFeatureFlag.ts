// Фиче-флаг новых типов виджетов (галерея компоновок, карточка 3e27dafe).
//
// Сервер знает восемь новых типов ВСЕГДА: они в нормализаторе
// (CANONICAL_TYPES) и в словаре SCHEMA валидатора секретаря. Так блок,
// который уже пришёл от роли, проходит без потерь.
//
// А вот перечислять новые типы в инструкции роли можно только когда клиент
// их рисует. Пока нативный рендер на Mac их не знает, роль, получив новый
// тип в инструкции, нарисует в чате пустой блок — а это хуже, чем не
// отправить блок вовсе. Поэтому список новых типов в инструкции включается
// флагом, а по умолчанию выключен.
//
// Включение: TASKFLOW_WIDGET_NEW_TYPES=1 (или on/true/yes).
// Выключение по умолчанию: переменная не задана, пуста или любое другое
// значение — секретарь продолжает работать на шести старых типах.

import { NEW_WIDGET_TYPES } from "./widgetContract.js";

const FLAG_VARS = ["TASKFLOW_WIDGET_NEW_TYPES"];

function readEnv(): string {
  for (const name of FLAG_VARS) {
    const value = process.env[name];
    if (value != null && value !== "") return value.trim().toLowerCase();
  }
  return "";
}

/** Включены ли новые типы в инструкции роли. По умолчанию — нет. */
export function newWidgetTypesEnabled(): boolean {
  return ["1", "on", "true", "yes"].includes(readEnv());
}

