// Состав команды (владелец 14.10.2026): у ролей не было общей картины —
// кто управляет, кто делает, кто проверяет и кому что передавать. Блок
// вкладывается в каждый ход: в системную инструкцию работы и в первый ход
// разговора в чате. Список ролей берётся из реестра, поэтому новая роль
// появляется у всех сразу; звено и обязанности известных ролей заданы здесь,
// у новой роли — звено «Прочие» и её описание из реестра.
import { allRoles } from "../roleRouting.js";

type Tier = { title: string; roles: Record<string, string> };

const TIERS: Tier[] = [
  { title: "Управление", roles: {
    code_orchestrator: "раскладывает работу по ролям, ведёт план, собирает результат воедино",
    secretary: "принимает поручения владельца, ставит задачи, готовит сводки, отвечает владельцу от лица команды",
  } },
  { title: "Проектирование", roles: {
    architect: "продумывает устройство системы до кода, когда решений несколько",
    researcher: "ищет и сравнивает варианты вне нашего кода, сводит найденное в выводы",
    analyst: "цифры, метрики, деньги",
    designer: "экраны и внешний вид; серверную логику не пишет",
  } },
  { title: "Исполнение", roles: {
    builder: "пишет и чинит код: сервер, приложение, веб",
    infra_engineer: "дежурит по серверу .110 и чинит поломки из «Состояния системы»",
  } },
  { title: "Проверка", roles: {
    critic_verifier: "проверяет сделанное и выносит вердикт",
    qa: "проходит сценарии в живом приложении и находит баги",
  } },
];

const RULES = [
  "Как передаётся работа: владелец ставит цель → Помощник владельца оформляет задачу → Оркестратор раскладывает её на этапы → исполнители делают → проверяющие принимают или возвращают на доработку → результат видит владелец.",
  "Решение по спорному или рискованному вопросу принимает владелец; Оркестратор — по распределению работы; Критик — по готовности результата. Не берись за чужое звено: увидел работу другой роли — предложи её Оркестратору, а не делай сам.",
];

export function teamStructureText(selfRole: string): string {
  const roles = allRoles().filter((r) => r.enabled);
  const known = new Set(TIERS.flatMap((t) => Object.keys(t.roles)));
  const line = (key: string, title: string, duty: string) => `- ${title}${key === selfRole ? " (это ты)" : ""} — ${duty}`;
  const blocks: string[] = ["Владелец — Максим: цели, приоритеты, последнее слово и приёмка результата."];
  for (const tier of TIERS) {
    const lines = Object.entries(tier.roles)
      .map(([key, duty]) => { const r = roles.find((x) => x.key === key); return r ? line(key, r.title, duty) : null; })
      .filter((x): x is string => x !== null);
    if (lines.length) blocks.push(`${tier.title}:\n${lines.join("\n")}`);
  }
  const others = roles.filter((r) => !known.has(r.key)).map((r) => line(r.key, r.title, r.summary || "обязанности описаны в её инструкции"));
  if (others.length) blocks.push(`Прочие:\n${others.join("\n")}`);
  return ["Состав команды TaskFlow.", ...blocks, ...RULES].join("\n\n");
}
