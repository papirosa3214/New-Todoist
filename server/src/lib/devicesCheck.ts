/**
 * Память о том, что таблицы `devices` в базе нет.
 *
 * Раньше это был обычный флаг на процесс: одна ошибка запроса — и он висел до
 * перезапуска. 10.11.2026 на .110 кончилось место, SQLite ответил ошибкой,
 * флаг включился, и до перезапуска службы перестали работать токены ВСЕХ
 * привязанных телефонов: приложение на 401 стирает токен и просит «войти
 * заново», хотя на самом деле всё цело.
 *
 * Теперь «таблицы нет» помнится окно в минуту: этого хватает, чтобы не бить
 * в базу на каждом запросе, и не хватает, чтобы разовая ошибка закрыла вход
 * навсегда.
 */
export const DEVICES_TABLE_RECHECK_MS = 60_000;

/** Пора ли снова спросить базу, есть ли таблица. */
export function devicesCheckSkipped(missing: boolean, since: number, now: number): boolean {
  if (!missing) return false;
  return now - since < DEVICES_TABLE_RECHECK_MS;
}
