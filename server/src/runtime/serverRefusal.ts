/** Отказы, которые выдаёт сам сервер, а не ошибка роли: вызов правильный,
 *  но сейчас не выполняется (пришло уточнение посреди хода, режим планирования).
 *  Владелец 27.10.2026: такие отказы не считать неверными вызовами — три
 *  подряд роняли ход роли, хотя отбивал его сам сервер. */
export const STEERING_REFUSAL="Действие не начато: поступило уточнение. Сначала учти новое сообщение, затем заново выбери нужные действия.";
export const PLANNING_REFUSAL="Планирование: разрешены только инструменты чтения. Для выполнения выберите режим Работа.";
export function isServerRefusal(text:string):boolean{
 return text.includes(STEERING_REFUSAL) || text.includes(PLANNING_REFUSAL);
}
