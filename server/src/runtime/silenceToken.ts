/**
 * Токен молчания (MAK-99, пункт 7 плана).
 *
 * Роль, у которой нет ни вопроса, ни нового факта, ни результата, не должна
 * занимать ленту темы. Раньше «принял, отвечу по message_id…» на 500–1800
 * знаков был обычным делом: сервер такие реплики публиковал, и чат темы
 * зарастал подтверждениями. У Гермеса бот без реплики заканчивает ход
 * токеном `[SILENT]` / `NO_REPLY`.
 *
 * Здесь — один классификатор «это пустое подтверждение, а не сообщение»:
 *   • явный токен `[SILENT]` / `[NO_REPLY]` гасит ход всегда;
 *   • короткая реплика из одних подтверждений («принял», «понял», «ок»,
 *     «принял, отвечу позже») тоже гасится;
 *   • всё, где есть вопрос, число, ссылка, код, слово результата или просто
 *     много текста, — остаётся сообщением.
 *
 * Функция чистая: тесты проверяют её без БД, а маршрут чата решает, куда
 * девать реплику (журнал) и что вернуть роли.
 */

/** Явный токен молчания — весь текст сообщения. */
const SILENCE_TOKEN = /^\s*\[(?:silent|no[_-]?reply)\]\s*$/i;

/** Слова-подтверждения: сами по себе не несут ни вопроса, ни результата. */
const ACK_WORDS = new Set([
  "принял", "приняла", "принято", "понял", "поняла", "понятно",
  "ок", "окей", "хорошо", "ладно", "ага", "ясно", "да", "угу",
  "договорились", "получил", "получила", "вижу", "спасибо", "благодарю",
  "на", "связи", "отпишусь", "маякну", "вернусь", "успел", "успела",
]);

/** Слова-обещания: подтверждение с обещанием ответить, но без самого ответа. */
const PROMISE_WORDS = new Set([
  "отвечу", "отвечу,", "позже", "сделаю", "приступлю", "сейчас", "буду",
  "жду", "жди", "проверю", "посмотрю", "подойду", "займусь",
]);

/** Маркеры вопроса/факта/результата — с ними реплика уже не молчание. */
const SUBSTANCE = /[?]|https?:\/\/|```|\bhttps?\b|\d|результат|готово|сделано|исправ|нашёл|нашел|вывод|ошибк|падает|падало|commit|коммит|дефект|тест/i;

/** Текст сообщения — пустое подтверждение (его не публикуем в ленте темы). */
export function isSilenceOnly(text: string | null | undefined): boolean {
  const raw = String(text ?? "");
  if (SILENCE_TOKEN.test(raw)) return true;
  if (raw.length > 240) return false;
  // Снимаем адресацию и метку слота: это часть протокола, не содержание.
  const stripped = raw
    .replace(/\[slot:[^\]]*\]/gi, " ")
    .replace(/@[\p{L}\p{N}_-]+/gu, " ")
    .trim();
  if (SUBSTANCE.test(stripped)) return false;
  const norm = stripped
    .toLowerCase()
    .replace(/[.,!;:…—–-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  if (!norm) return true;
  const words = norm.split(" ").filter(Boolean);
  if (words.length > 10) return false;
  return words.every((w) => ACK_WORDS.has(w) || PROMISE_WORDS.has(w));
}
